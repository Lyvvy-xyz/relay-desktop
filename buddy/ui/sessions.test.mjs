import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
const source = await readFile(new URL("./sessions.js", import.meta.url), "utf8");
const { deriveSession } = await import(`data:text/javascript;base64,${Buffer.from(source).toString("base64")}`);
const user = { kind: "user", text: "Build" };
const start = { kind: "tool_start", id: "1", tool: "Read", summary: "panel.js" };
const end = (ok) => ({ kind: "tool_end", id: "1", ok });
const done = { kind: "done" };
assert.equal(deriveSession(undefined, [], 100).state, "idle");
const working = deriveSession(undefined, [user, start], 100);
assert.equal(working.state, "working");
assert.equal(working.startedAt, 100);
assert.equal(deriveSession(working, [], 200).startedAt, 100);
const failed = deriveSession(working, [end(false)], 200);
assert.equal(failed.state, "failed");
assert.equal(working.steps[0].state, "running", "does not mutate the previous state");
assert.equal(deriveSession(failed, [{ ...start, id: "2" }], 300).state, "failed");
assert.equal(deriveSession(failed, [end(true)], 300).state, "working");
const finished = deriveSession(failed, [{ kind: "text", text: "Finished\nMore" }, done], 400);
assert.equal(finished.state, "done");
assert.equal(finished.text, "Finished");
assert.equal(finished.endedAt, 400);
assert.equal(deriveSession(undefined, [user, start, done], null).startedAt, null);
const seenLate = deriveSession(undefined, [user, start], null);
assert.equal(deriveSession(seenLate, [end(true)], 200).startedAt, null, "a turn already under way stays unknown");
const next = deriveSession(finished, [user], 600);
assert.equal(deriveSession(finished, [user, start, done], 600).endedAt, 600);
assert.equal(deriveSession(undefined, [user, start, end(false)], null).startedAt, null);
assert.equal(next.state, "working");
assert.equal(next.startedAt, 600);
assert.equal(next.endedAt, null);
assert.deepEqual(next.steps, []);
assert.equal(next.text, "");
assert.equal(deriveSession(finished, [start], 700).state, "working");
assert.equal(deriveSession(undefined, [start], 800).state, "working");
assert.equal(deriveSession(undefined, [{ kind: "tool_end", id: "missing", ok: false }], 900).state, "failed");
assert.equal(deriveSession(undefined, [done], 900).startedAt, null);
assert.equal(deriveSession(undefined, [{ kind: "text", text: "a".repeat(200) }, done], 900).text.length, 160);
assert.equal(deriveSession(undefined, Array.from({ length: 40 }, (_, id) => ({ ...start, id })), 1000).steps.length, 30);
console.log("Sessions state, turn timing, incremental history, and immutability tests passed.");
